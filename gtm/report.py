"""Turns a run into the morning scoreboard (markdown) and a JSON summary."""
from __future__ import annotations

from collections import Counter


def _pct(x):
    return "n/a" if x is None else f"{x:.2%}"


def summary(r: dict) -> dict:
    accts = r["accounts"]
    return {
        "as_of": r["as_of"],
        "raw_signals": r["signals"],
        "accounts_after_dedupe": len(accts),
        "tiers": dict(Counter(a["tier"] for a in accts)),
        "actions": dict(Counter(a["action"] for a in accts)),
        "drafts": len(r["drafts"]),
        "drafts_failing_lint": sum(1 for d in r["drafts"] if d["lint"]),
        "replies": dict(Counter(x["label"] for x in r["replies"])),
        "mailboxes": dict(Counter(m["status"] for m in r["mailboxes"])),
        "domains_to_retire": [d["domain"] for d in r["domains"] if d["verdict"] != "keep"],
        "final_states": dict(Counter(r["states"].values())),
    }


def scoreboard(r: dict) -> str:
    s = summary(r)
    accts = r["accounts"]
    L = []
    L.append(f"# Engine scoreboard: {r['as_of']}")
    L.append("")
    L.append("> Generated by `python -m gtm run`. All businesses, domains and numbers are synthetic.")
    L.append("")
    L.append("## Funnel")
    L.append("")
    L.append("| Stage | Count |")
    L.append("|---|---|")
    L.append(f"| Raw signals ingested | {s['raw_signals']} |")
    L.append(f"| Accounts after dedupe | {s['accounts_after_dedupe']} |")
    for t in ("A", "B", "C", "D", "DQ"):
        if t in s["tiers"]:
            L.append(f"| Tier {t} | {s['tiers'][t]} |")
    L.append(f"| Drafts rendered | {s['drafts']} |")
    L.append(f"| Drafts failing lint | {s['drafts_failing_lint']} |")
    L.append("")

    L.append("## Today's call and visit list")
    L.append("")
    L.append("| Due | Type | Account | Why |")
    L.append("|---|---|---|---|")
    tasks = sorted((a for a in accts if a["task"]), key=lambda a: a["task"]["due"])
    for a in tasks:
        L.append(f"| {a['task']['due'].replace('T', ' ')} | {a['task']['type']} | {a['business_name']} ({a['city']}) | {'; '.join(a['reasons'][:2])} |")
    L.append("")

    L.append("## Ranked accounts")
    L.append("")
    L.append("| # | Account | Lane | Score | Tier | Action | Top reasons |")
    L.append("|---|---|---|---|---|---|---|")
    for i, a in enumerate(accts, 1):
        L.append(f"| {i} | {a['business_name']} | {a['lane'] or '-'} | {a['score']} | {a['tier']} | {a['action']} | {'; '.join(a['reasons'][:3])} |")
    L.append("")

    L.append("## Replies")
    L.append("")
    L.append("| Reply | From | Label | Next | Result |")
    L.append("|---|---|---|---|---|")
    for x in r["replies"]:
        extra = x.get("follow_up_on") or x.get("resume_on") or x.get("referred_email") or ""
        nxt = x["next_action"] + (f" ({extra})" if extra else "")
        L.append(f"| {x['id']} | {x.get('business_name') or x['from']} | {x['label']} | {nxt} | {x.get('applied', '')} |")
    L.append("")

    L.append("## Deliverability")
    L.append("")
    L.append("| Mailbox | Domain | Status | Bounce | Complaints | Notes |")
    L.append("|---|---|---|---|---|---|")
    for m in r["mailboxes"]:
        L.append(f"| {m['id']} | {m['domain']} | {m['status']} | {_pct(m['bounce_rate'])} | {_pct(m['complaint_rate'])} | {'; '.join(m['reasons'])} |")
    L.append("")
    for d in r["domains"]:
        if d["verdict"] != "keep":
            L.append(f"**{d['domain']}**: {d['paused']} of {d['mailboxes']} mailboxes paused. Verdict: {d['verdict']}.")
            L.append("")

    L.append("## Copy variants")
    L.append("")
    L.append("| Sequence | Variant | Sent | Reply rate | Positive rate | Read |")
    L.append("|---|---|---|---|---|---|")
    for v in r["variants"]:
        L.append(f"| {v['sequence']} | {v['variant']} | {v['sent']} | {_pct(v['reply_rate'])} | {_pct(v['positive_rate'])} | {v['verdict'] or v['flag']} |")
    L.append("")

    bad = [t for t in r["template_lint"] if t["issues"]]
    L.append("## Template lint")
    L.append("")
    L.append(f"{len(r['template_lint'])} opener x step combinations checked, {len(bad)} with issues.")
    for t in bad:
        L.append(f"- {t['sequence']} day {t['day']} {t['variant']} / {t['opener']}: {'; '.join(t['issues'])}")
    L.append("")
    L.append("## End states")
    L.append("")
    for k, v in sorted(s["final_states"].items(), key=lambda kv: -kv[1]):
        L.append(f"- {k}: {v}")
    L.append("")
    return "\n".join(L)


def drafts_md(drafts: list[dict], routed: list[dict]) -> str:
    names = {a["account_id"]: a for a in routed}
    L = ["# Drafts awaiting approval", "",
         "Every email below passed the lint gate. Call steps are scripts for the rep.", ""]
    current = None
    for d in drafts:
        if d["account_id"] != current:
            current = d["account_id"]
            a = names[current]
            L += [f"## {a['business_name']} ({a['city']})",
                  f"`{d['sequence']}` variant {d['variant']}, opener from signal `{d['opener']}`", ""]
        if d["channel"] == "email":
            L += [f"**Day {d['day']} email.** Subject: `{d['subject']}`", ""]
            L += ["> " + line if line else ">" for line in d["body"].split("\n")]
            if d["lint"]:
                L += ["", f"LINT FAILED: {'; '.join(d['lint'])}"]
        else:
            L += [f"**Day {d['day']} {d['channel']}.** {d['body']}"]
        L.append("")
    return "\n".join(L)
