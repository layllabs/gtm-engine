"""Write the reply classifier's per-case eval results to docs/eval_results.md
and docs/eval_results.json so the portfolio shows the confusion, not just
the headline number. Run after changing rules or the labeled set:

    python scripts/export_eval.py
"""
import json
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from gtm.replies import classify  # noqa: E402
from gtm.util import read_jsonl  # noqa: E402

SET = ROOT / "data" / "sample" / "reply_eval.jsonl"


def run() -> dict:
    rows = []
    for r in read_jsonl(SET):
        got, conf = classify(r["body"])
        rows.append({"body": r["body"], "expected": r["label"], "got": got, "confidence": conf, "correct": got == r["label"]})
    per_label = {}
    for lbl in sorted({r["expected"] for r in rows}):
        sub = [r for r in rows if r["expected"] == lbl]
        per_label[lbl] = {"n": len(sub), "correct": sum(r["correct"] for r in sub)}
    confusion = Counter((r["expected"], r["got"]) for r in rows if not r["correct"])
    return {
        "set": str(SET.relative_to(ROOT)),
        "n": len(rows),
        "correct": sum(r["correct"] for r in rows),
        "per_label": per_label,
        "confusions": [{"expected": e, "got": g, "count": c} for (e, g), c in confusion.most_common()],
        "rows": rows,
    }


def markdown(res: dict) -> str:
    L = ["# Reply classifier eval results", "",
         f"Rules in `gtm/replies.py` against `{res['set']}`. "
         f"{res['correct']}/{res['n']} correct. Generated by `scripts/export_eval.py`; CI fails below 90%.", "",
         "## Per label", "", "| label | n | correct |", "|---|---|---|"]
    for lbl, v in res["per_label"].items():
        L.append(f"| {lbl} | {v['n']} | {v['correct']} |")
    L += ["", "## Confusions", ""]
    if res["confusions"]:
        L += ["| expected | got | count |", "|---|---|---|"]
        L += [f"| {c['expected']} | {c['got']} | {c['count']} |" for c in res["confusions"]]
    else:
        L.append("None on the current set. That says the set is small, not that the rules are done. "
                 "Every new real reply that the rules get wrong gets added here with its correct label.")
    L += ["", "## Every case", "", "| expected | got | conf | reply |", "|---|---|---|---|"]
    for r in res["rows"]:
        mark = "" if r["correct"] else " **(miss)**"
        L.append(f"| {r['expected']} | {r['got']}{mark} | {r['confidence']:.1f} | {r['body'][:90].replace('|', '/')} |")
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    res = run()
    (ROOT / "docs" / "eval_results.json").write_text(json.dumps(res, indent=2) + "\n")
    (ROOT / "docs" / "eval_results.md").write_text(markdown(res))
    print(f"{res['correct']}/{res['n']} correct, wrote docs/eval_results.md and .json")
